import type { SnackbarSeverity } from './store'

const includesAny = (text: string, parts: string[]) =>
  parts.some(part => text.includes(part))

export const inferSnackbarSeverity = (message: string): SnackbarSeverity => {
  const normalized = message.trim().toLowerCase()

  if (!normalized) {
    return 'info'
  }

  if (
    includesAny(normalized, [
      'не удалось',
      'ошибк',
      'неверн',
      'недейств',
      'просроч',
      'fail',
      'invalid',
    ])
  ) {
    return 'error'
  }

  if (
    includesAny(normalized, [
      'подтвердите',
      'подтвердить почту',
      'не совпадают',
      'лимит',
      'максимум',
      'не больше',
      'выберите',
      'заполните',
      'проверьте',
      'упакуйте',
    ])
  ) {
    return 'warning'
  }

  if (
    includesAny(normalized, [
      'успеш',
      'сохранен',
      'сохранён',
      'обновлен',
      'обновлён',
      'отправлен',
      'скопирован',
      'переключ',
      'подтвержден',
      'опубликован',
      'создан',
      'создана',
      'удалён',
      'удален',
      'возвращен',
      'в архив',
      'из архива',
      'приватн',
      'публичн',
      'отклонён',
      'отклонен',
      'аннулир',
      'перенесён',
      'перенесен',
      'добавлен',
      'готов',
      'шаблон',
      'ответственный',
      'настройки уведомлений сохранены',
      'настройки дашборда сохранены',
      'связь с профилем удалена',
      'аватар обновлён',
      'баннер обновлён',
      'статус успешно',
      'тз отправлено',
      'файл отправлен',
      'ссылка на',
      'отключена',
      'интеграция отключена',
      'отклик отклонён',
      'задача аннулирована',
      'дедлайн перенесён',
      'пост перемещен',
      'объявление перемещено',
      'объявление возвращено',
      'пост возвращен',
      'пост сделан',
      'объявление сделано',
      'задача возвращена',
      'задача сохранена',
      'пост успешно',
      'ссылка скопирована',
      'данные успешно',
      'письмо для подтверждения',
      'дублир',
    ])
  ) {
    return 'success'
  }

  return 'info'
}
